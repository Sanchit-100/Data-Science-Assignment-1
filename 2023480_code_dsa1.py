rng = np.random.default_rng(seed + 6)
subset = rng.choice(n, 50000, replace=False)
small_x = X[subset]
small_y = y[subset]
small_b = np.linalg.lstsq(small_x, small_y, rcond=None)[0]
small_loss = np.sum((small_x @ small_b - small_y) ** 2)
rng = np.random.default_rng(seed + 7)
m = 500
rows = []
for method in ['CountSketch', 'Gaussian']:
    for run in range(5):
        start = perf_counter()
        if method == 'CountSketch':
            sx, sy = count_sketch(small_x, small_y, m, rng)
        else:
            S = rng.normal(0, 1 / np.sqrt(m), (m, len(small_x)))
            sx = S @ small_x
            sy = S @ small_y
        sketch_time = perf_counter() - start
        a = np.linalg.lstsq(sx, sy, rcond=None)[0]
        loss = np.sum((small_x @ a - small_y) ** 2)
        rows.append([method, run + 1, sketch_time, loss, loss / small_loss])
        if method == 'Gaussian':
            del S

q2_compare = pd.DataFrame(rows, columns=['method', 'run', 'time', 'loss', 'ratio'])
q2_methods = q2_compare.groupby('method').agg(
    mean_time=('time', 'mean'), mean_ratio=('ratio', 'mean'))
print('Q2(e) Subset rows:', len(subset), 'Subset baseline loss:', small_loss)
print(q2_compare.to_string(index=False))
