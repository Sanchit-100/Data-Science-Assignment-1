import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import sklearn
from time import perf_counter
from sklearn.datasets import fetch_kddcup99
from sklearn.cluster import KMeans
from sklearn.metrics import pairwise_distances_argmin_min as nearest_centres
from threadpoolctl import threadpool_limits

seed = 42
thread_limit = threadpool_limits(limits=2)
pd.set_option('display.max_columns', None)
print('NumPy:', np.__version__, 'scikit-learn:', sklearn.__version__)

kdd = fetch_kddcup99(subset=None, as_frame=True)
text_cols = ['protocol_type', 'service', 'flag']
data = pd.get_dummies(kdd.data, columns=text_cols, dtype=np.float32)
data = data.astype(np.float32)
drop_cols = data.columns[data.nunique() == 1].tolist()
data = data.drop(columns=drop_cols)
data = (data - data.min()) / (data.max() - data.min())
X = data.to_numpy(dtype=np.float32)
y = (kdd.target != b'normal.').to_numpy(dtype=float)
n, d = X.shape
print('Rows:', n, 'Columns:', d)
print('Dropped columns:', drop_cols)
print('Normal:', int((y == 0).sum()), 'Attack:', int(y.sum()))
del data, kdd

def cluster_cost(data, centres):
    nearest, distances = nearest_centres(data, centres)
    return np.sum(distances.astype(float) ** 2)

def cluster_mean(data, labels):
    return np.array([data[labels == j].mean(axis=0, dtype=float) for j in range(15)])

def count_sketch(data, target, m, rng):
    buckets = rng.integers(0, m, len(data))
    signs = rng.choice([-1, 1], len(data)).astype(np.float32)
    sx = np.zeros((m, data.shape[1]))
    sy = np.zeros(m)
    np.add.at(sx, buckets, data * signs[:, None])
    np.add.at(sy, buckets, target * signs)
    return sx, sy

start = perf_counter()
base_model = KMeans(n_clusters=15, n_init=5, random_state=seed).fit(X)
base_time = perf_counter() - start
base_labels = base_model.labels_
base_cost = cluster_cost(X, base_model.cluster_centers_)
print('Q1(a) Cost:', base_cost, 'Time (s):', base_time)

rng = np.random.default_rng(seed + 1)
m_values = [5, 10, 15, 20, 25]
rows = []
for m in m_values:
    for run in range(5):
        R = rng.normal(0, 1 / np.sqrt(m), (d, m)).astype(np.float32)
        start = perf_counter()
        Y = X @ R
        model = KMeans(n_clusters=15, n_init=5, random_state=seed).fit(Y)
        run_time = perf_counter() - start
        centres = cluster_mean(X, model.labels_)
        cost = cluster_cost(X, centres)
        plus_centres = model.cluster_centers_ @ np.linalg.pinv(R)
        plus_cost = cluster_cost(X, plus_centres)
        rows.append([m, run + 1, cost, cost / base_cost, plus_cost,
                     plus_cost / base_cost, run_time])
    print('Finished Q1(b)-(d), m =', m)

q1_runs = pd.DataFrame(rows, columns=['m', 'run', 'cost', 'ratio',
                                    'plus_cost', 'plus_ratio', 'time'])
q1_table = q1_runs.groupby('m').agg(
    mean_ratio=('ratio', 'mean'), min_ratio=('ratio', 'min'),
    max_ratio=('ratio', 'max'), plus_mean=('plus_ratio', 'mean'),
    plus_min=('plus_ratio', 'min'), plus_max=('plus_ratio', 'max'),
    mean_time=('time', 'mean'))
print(q1_runs.to_string(index=False))
print('\nQ1(b)-(d) Summary\n', q1_table.to_string())

plt.figure(figsize=(8, 4))
plt.plot(q1_table.index, q1_table['mean_time'], 'o-', label='Projection + k-means')
plt.axhline(base_time, color='red', linestyle='--', label='Original k-means')
plt.xlabel('Projection dimension m')
plt.ylabel('Mean time (seconds)')
plt.title('Q1(d): Clustering time')
plt.xticks(m_values)
plt.legend()
plt.tight_layout()
plt.show()

rng = np.random.default_rng(seed + 2)
pair_i = np.array([], dtype=int)
pair_j = np.array([], dtype=int)
zero_pairs = 0
while len(pair_i) < 10000:
    size = 10000 - len(pair_i)
    i = rng.integers(0, n, size)
    j = (i + rng.integers(1, n, size)) % n
    distances = np.sum((X[i].astype(float) - X[j]) ** 2, axis=1)
    valid = distances > 0
    zero_pairs += int((~valid).sum())
    pair_i = np.concatenate([pair_i, i[valid]])
    pair_j = np.concatenate([pair_j, j[valid]])

pair_diff = X[pair_i].astype(float) - X[pair_j]
pair_dist = np.sum(pair_diff ** 2, axis=1)
pair_ratios = []
for m in m_values:
    R = rng.normal(0, 1 / np.sqrt(m), (d, m))
    pair_ratios.append(np.sum((pair_diff @ R) ** 2, axis=1) / pair_dist)
print('Q1(e) Valid pairs:', len(pair_i), 'Zero-distance pairs redrawn:', zero_pairs)

rng = np.random.default_rng(seed + 3)
centres = cluster_mean(X, base_labels)
centred = X - centres[base_labels]
part_cost = np.sum(centred ** 2)
part_ratios = []
for m in m_values:
    ratios = []
    for run in range(20):
        R = rng.normal(0, 1 / np.sqrt(m), (d, m))
        ratios.append(np.sum((centred @ R) ** 2) / part_cost)
    part_ratios.append(ratios)
    print('Finished Q1(e), m =', m)

q1_spread = pd.DataFrame({
    'm': m_values,
    'pair_mean': [np.mean(a) for a in pair_ratios],
    'pair_std': [np.std(a) for a in pair_ratios],
    'part_mean': [np.mean(a) for a in part_ratios],
    'part_std': [np.std(a) for a in part_ratios]})
print('Fixed-partition cost:', part_cost)
print(q1_spread.to_string(index=False))

fig, axes = plt.subplots(1, 2, figsize=(12, 4), sharey=True)
for ax, values, title in zip(axes, [pair_ratios, part_ratios],
                             ['10,000 pair-distance ratios', '20 fixed-partition ratios']):
    ax.boxplot(values, tick_labels=m_values, showfliers=False)
    ax.axhline(1, color='red', linestyle='--')
    ax.set_xlabel('Projection dimension m')
    ax.set_title(title)
axes[0].set_ylabel('Projected / original squared distance or cost')
fig.suptitle('Q1(e): Distance and partition-cost distortion')
plt.tight_layout()
plt.show()
del centred, Y

start = perf_counter()
b, residuals, rank, singular = np.linalg.lstsq(X, y, rcond=None)
full_time = perf_counter() - start
residual = X @ b - y
full_loss = np.sum(residual ** 2)
print('Q2(a) Loss:', full_loss, 'Time (s):', full_time)
print('Rank of X:', rank)

rng = np.random.default_rng(seed + 4)
sketch_sizes = [50, 100, 200, 500, 1000, 2000, 5000]
rows = []
for m in sketch_sizes:
    for run in range(5):
        start = perf_counter()
        sx, sy = count_sketch(X, y, m, rng)
        a = np.linalg.lstsq(sx, sy, rcond=None)[0]
        run_time = perf_counter() - start
        loss = np.sum((X @ a - y) ** 2)
        sketch_loss = np.sum((sx @ a - sy) ** 2)
        rows.append([m, run + 1, loss, loss / full_loss, sketch_loss, run_time])
    print('Finished Q2(b)-(c), m =', m)

q2_runs = pd.DataFrame(rows, columns=['m', 'run', 'loss', 'ratio', 'sketch_loss', 'time'])
q2_table = q2_runs.groupby('m').agg(
    mean_ratio=('ratio', 'mean'), min_ratio=('ratio', 'min'),
    max_ratio=('ratio', 'max'), mean_sketch=('sketch_loss', 'mean'),
    mean_time=('time', 'mean'))
print(q2_runs.to_string(index=False))
print('\nQ2(b)-(c) Summary\n', q2_table.to_string())

errors = np.array([q2_table['mean_ratio'] - q2_table['min_ratio'],
                   q2_table['max_ratio'] - q2_table['mean_ratio']])
plt.figure(figsize=(8, 4))
plt.errorbar(sketch_sizes, q2_table['mean_ratio'], yerr=errors, fmt='o-', capsize=4)
plt.axhline(1, color='red', linestyle='--', label='Full solution')
plt.axvline(rank, color='grey', linestyle=':', label='Rank of X')
plt.xscale('log')
plt.yscale('log')
plt.xlabel('Sketch rows m')
plt.ylabel('Mean full-data loss ratio')
plt.title('Q2(b): Regression loss ratios with minimum/maximum error bars')
plt.legend()
plt.tight_layout()
plt.show()

plt.figure(figsize=(8, 4))
